export function distanceToLine(x, z, line) {
  let best = Infinity,
    point = null;
  for (let i = 1; i < line.length; i++) {
    const a = line[i - 1],
      b = line[i],
      dx = b[0] - a[0],
      dz = b[1] - a[1],
      t = Math.max(
        0,
        Math.min(1, ((x - a[0]) * dx + (z - a[1]) * dz) / (dx * dx + dz * dz)),
      );
    const p = { x: a[0] + dx * t, z: a[1] + dz * t },
      d = Math.hypot(x - p.x, z - p.z);
    if (d < best) {
      best = d;
      point = p;
    }
  }
  return { distance: best, point };
}
export function smoothLine(line) {
  // Two Chaikin passes make continuous bends without tessellating flat ground.
  let out = line;
  for (let n = 0; n < 2; n++) {
    const v = [out[0]];
    for (let i = 1; i < out.length; i++) {
      const a = out[i - 1],
        b = out[i];
      v.push(
        [a[0] * 0.75 + b[0] * 0.25, a[1] * 0.75 + b[1] * 0.25],
        [a[0] * 0.25 + b[0] * 0.75, a[1] * 0.25 + b[1] * 0.75],
      );
    }
    v.push(out.at(-1));
    out = v;
  }
  return out;
}
